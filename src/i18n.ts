/** 占位符填充："...{n}..." → 用参数依次替换 */
export function fmt(tpl: string, ...args: (string | number)[]): string {
  let out = tpl;
  for (const a of args) out = out.replace("{n}", String(a));
  return out;
}

/** 两个占位符版本（{n}/{m}） */
export function fmt2(tpl: string, n: string | number, m: string | number): string {
  return tpl.replace("{n}", String(n)).replace("{m}", String(m));
}

/** 单条双语："中文 / English"（codicon 前缀相同则只保留一份） */
export function bb(key: string): string {
  const zh = STRINGS.zh[key];
  const en = STRINGS.en[key];
  if (typeof zh !== "string" || typeof en !== "string") return (zh ?? en ?? key) as any;
  if (zh === en) return zh;
  const mz = zh.match(/^(\$\([^)]+\)\s*)(.*)$/);
  const me = en.match(/^(\$\([^)]+\)\s*)(.*)$/);
  if (mz && me && mz[1] === me[1]) return mz[1] + mz[2] + " / " + me[2];
  return zh + " / " + en;
}

/** 双语字典视图：宿主侧原生对话框（QuickPick/弹窗）直接中英同时展示，不随面板语言切换 */
export function bilingual(): Record<string, any> {
  return new Proxy({} as Record<string, any>, {
    get: (_t, k) => bb(String(k)),
  });
}
